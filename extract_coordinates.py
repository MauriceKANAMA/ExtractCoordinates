import os.path

from qgis.PyQt.QtCore import QCoreApplication, QLocale, QTranslator
from qgis.PyQt.QtGui import QIcon
from qgis.PyQt.QtWidgets import QAction
from qgis.core import QgsApplication, QgsSettings

from .coordonnees_algorithm import CoordinatesProvider


class ExtractCoordinates:
    """Plugin QGIS qui ajoute l'algorithme d'extraction des sommets."""

    def __init__(self, iface):
        """Constructeur.

        :param iface: Interface QGIS fournie au plugin.
        :type iface: QgsInterface
        """
        self.iface = iface
        self.plugin_dir = os.path.dirname(__file__)
        locale = QgsSettings().value('locale/userLocale', QLocale().name())[0:2]
        locale_path = os.path.join(self.plugin_dir, 'i18n', f'{locale}.qm')
        self.translator = None
        if os.path.exists(locale_path):
            self.translator = QTranslator()
            self.translator.load(locale_path)
            QCoreApplication.installTranslator(self.translator)
        self.actions = []
        self.menu = self.tr('&Extract Coordinates')
        self.provider = None

    def tr(self, message):
        """Retourne la traduction du message."""
        return QCoreApplication.translate('ExtractCoordinates', message)

    def add_action(self, icon_path, text, callback, enabled_flag=True,
                   add_to_menu=True, add_to_toolbar=True,
                   status_tip=None, whats_this=None, parent=None):
        """Ajoute une icône à la barre d'outils et une entrée au menu."""
        icon = QIcon(icon_path)
        action = QAction(icon, text, parent)
        action.triggered.connect(callback)
        action.setEnabled(enabled_flag)

        if status_tip is not None:
            action.setStatusTip(status_tip)
        if whats_this is not None:
            action.setWhatsThis(whats_this)
        if add_to_toolbar:
            self.iface.addToolBarIcon(action)
        if add_to_menu:
            self.iface.addPluginToMenu(self.menu, action)

        self.actions.append(action)
        return action

    def initGui(self):
        """Crée l'icône, le menu et enregistre l'algorithme dans QGIS."""
        self.provider = CoordinatesProvider()
        QgsApplication.processingRegistry().addProvider(self.provider)

        icon_path = os.path.join(self.plugin_dir, 'icon.png')
        self.add_action(
            icon_path,
            text=self.tr('Extraire les sommets'),
            callback=self.run,
            parent=self.iface.mainWindow())

    def unload(self):
        """Retire l'algorithme, le menu et l'icône de QGIS."""
        if self.translator is not None:
            QCoreApplication.removeTranslator(self.translator)
        QgsApplication.processingRegistry().removeProvider(self.provider)
        for action in self.actions:
            self.iface.removePluginMenu(self.menu, action)
            self.iface.removeToolBarIcon(action)
        self.actions = []

    def run(self):
        """Ouvre la boîte de dialogue de l'algorithme d'extraction."""
        from qgis import processing
        processing.execAlgorithmDialog(
            'extraction_coordonnees:extraction_sommets', {})
